# Regenerates launcher/ui/zero/ZeroMarkData.h from program_info/zero-logo-minecraft.svg (16x16 cells of 16 px).
import re, sys
svg = open(sys.argv[1], encoding="utf-8").read()
grid = [[None] * 16 for _ in range(16)]
for m in re.finditer(r'<rect x="(\d+)" y="(\d+)" width="(\d+)" height="(\d+)" fill="#([0-9A-Fa-f]{6})"', svg):
    x, y, w, h = (int(m.group(i)) for i in range(1, 5))
    col = m.group(5).upper()
    for cy in range(y // 16, (y + h) // 16):
        for cx in range(x // 16, (x + w) // 16):
            grid[cy][cx] = col
cols = []
for row in grid:
    for c in row:
        if c and c not in cols:
            cols.append(c)
chars = "abcdefghijklmnop"
rows = ["".join("." if c is None else chars[cols.index(c)] for c in row) for row in grid]
out = ["// SPDX-License-Identifier: GPL-3.0-only",
       "// Generated by installer/tools/gen_mark.py from program_info/zero-logo-minecraft.svg. Do not edit by hand.",
       "#pragma once", "#include <QtGlobal>", "", "namespace Zero::Scene::MarkData {",
       "inline constexpr int kCells = 16;",
       "// '.' = transparent, a..p index kPalette (the colours of the app mark, which is artwork, not a UI token).",
       "inline constexpr const char* kRows[16] = {"]
out += ['    "%s",' % r for r in rows]
out += ["};", "inline constexpr quint32 kPalette[] = {"]
out += ["    0xFF%s," % c for c in cols]
out += ["};", "}  // namespace Zero::Scene::MarkData", ""]
open(sys.argv[2], "w", encoding="utf-8", newline="\n").write("\n".join(out))
print(len(cols), "colours;", sum(r.count(".") for r in rows), "transparent cells")
